import os
from openai import OpenAI

# Kunin ang API key mula sa environment variables ng GitHub Actions
client = OpenAI(api_key=os.environ.get("OPENAI_API_KEY"))

# Humingi ng simpleng file o nilalaman sa OpenAI
response = client.chat.completions.create(
    model="gpt-4o-mini",
    messages=[
        {"role": "system", "content": "Ikaw ay isang helpful coding assistant."},
        {"role": "user", "content": "Gumawa ng simpleng README.md file na may malaking pamagat at pagbati sa Tagalog."}
    ]
)

content = response.choices[0].message.content

# Isulat ang sagot ng AI sa isang bagong file
with open("AI_GENERATED.md", "w", encoding="utf-8") as f:
    f.write(content)

print("File successfully generated by AI!")
